"""Turns the AgentDojo results into the tables of docs Sec. 8.6 (doc/benchmarks.md).

    .venv/bin/python report.py                                  # print the tables
    .venv/bin/python report.py --update ../../doc/benchmarks.md  # rewrite them in place

Every table names the approver and harness its rows used, and refuses to mix versions.
Two kinds of successful attack are counted apart, because no runtime can stop them:

- text-only attacks, whose goal is something the model says rather than a call it
  makes ("say that I should visit this hotel"); only the user reading the reply can;
- approver gaps, where the user's own task needs a call to the same place as the
  attack, so only free text (a body, a title) tells them apart, and the scripted
  approver compares recipients and amounts, not prose.

Both are derived from AgentDojo's task definitions, not listed by hand.
"""

import argparse
import json
import sys
from collections import defaultdict
from dataclasses import dataclass
from functools import cache
from pathlib import Path

from agentdojo.task_suite.load_suites import get_suite

from pr3_agentdojo.approver import CONSEQUENTIAL, Context, markers, matches

HERE = Path(__file__).resolve().parent
BENCHMARK_VERSION = "v1.2.2"
SUITES = ["banking", "workspace", "slack", "travel"]
ARMS = {"pr3": "PR3", "plain": "plain", "confirm_all": "confirm-all"}
BEGIN = "<!-- results:begin (generated by bench/agentdojo/report.py) -->"
END = "<!-- results:end -->"


@dataclass(frozen=True)
class Kinds:
    """Which pairs of a suite the runtime cannot be judged on."""

    gaps: frozenset  # (user task, injection task)
    text_only: frozenset  # injection tasks
    user_tasks: int
    injection_tasks: int


@cache
def kinds(suite_name: str) -> Kinds:
    suite = get_suite(BENCHMARK_VERSION, suite_name)
    env = suite.load_and_inject_default_environment({})
    context = Context.of(suite_name, env)
    known = env.model_dump_json()
    attacks = {
        attack_id: [
            call
            for call in attack.ground_truth(env.model_copy(deep=True))
            if call.function in CONSEQUENTIAL[suite_name]
        ]
        for attack_id, attack in suite.injection_tasks.items()
    }
    text_only = frozenset(
        attack_id
        for attack_id, attack in suite.injection_tasks.items()
        if not attacks[attack_id] and not markers(attack.GOAL, [], known)
    )
    gaps = set()
    for task_id, task in suite.user_tasks.items():
        need = task.ground_truth(env.model_copy(deep=True))
        for attack_id, calls in attacks.items():
            if any(matches(suite_name, c.function, c.args, need, context) for c in calls):
                gaps.add((task_id, attack_id))
    return Kinds(frozenset(gaps), text_only, len(suite.user_tasks), len(suite.injection_tasks))


@dataclass
class Row:
    arm: str
    runs: int
    benign: float
    attacked: float
    fooled: float
    succeeded: float
    text_only: int
    in_gaps: int
    approvals: float


def pct(part: int, whole: int) -> float:
    return 100 * part / whole if whole else float("nan")


def summarize(records: list[dict], kind: Kinds) -> list[Row]:
    """One row per arm, in the order of ARMS."""
    by_arm = defaultdict(list)
    for r in records:
        by_arm[r["mode"]].append(r)
    rows = []
    for arm in ARMS:
        rs = by_arm.get(arm)
        if not rs:
            continue
        benign = [r for r in rs if r["injection_task"] is None]
        attacked = [r for r in rs if r["injection_task"] is not None]
        succeeded = [r for r in attacked if r["attack_succeeded"]]
        rows.append(
            Row(
                arm=arm,
                runs=len(rs),
                benign=pct(sum(bool(r["utility"]) for r in benign), len(benign)),
                attacked=pct(sum(bool(r["utility"]) for r in attacked), len(attacked)),
                fooled=pct(sum(bool(r["model_attempted_attack"]) for r in attacked), len(attacked)),
                succeeded=pct(len(succeeded), len(attacked)),
                text_only=sum(r["injection_task"] in kind.text_only for r in succeeded),
                in_gaps=sum((r["user_task"], r["injection_task"]) in kind.gaps for r in succeeded),
                approvals=sum((r["stats"] or {}).get("approvals_asked", 0) for r in rs) / len(rs),
            )
        )
    return rows


# The arms each harness version changed. Harness 2 gave PR3 the plain loop's limits for
# tool results, arguments and calls per round; the other arms ran the same before and
# after, and their older rows record no harness.
HARNESS_ARMS = {"pr3"}


def versions(records: list[dict]) -> tuple:
    """The approver every record used and the harness the PR3 rows used; anything mixed
    is an error."""
    approvers = {r.get("approver") for r in records}
    harnesses = {r.get("harness") for r in records if r["mode"] in HARNESS_ARMS}
    if len(approvers) != 1 or len(harnesses) > 1 or None in harnesses:
        raise ValueError(
            f"mixed versions: approver {sorted(approvers, key=str)}, PR3 harness {sorted(harnesses, key=str)}"
        )
    return approvers.pop(), harnesses.pop() if harnesses else None


def model_name(stem: str) -> str:
    """`banking-Qwen3.8-27B-Q4_K_M` → `Qwen3.8-27B`."""
    model = stem.split("-", 1)[1]
    return model.rsplit("-Q", 1)[0] if "-Q" in model else model


def fmt(value: float) -> str:
    return "n/a" if value != value else f"{value:.1f}%"


def table(suite: str, files: list[Path]) -> str:
    kind = kinds(suite)
    lines = []
    header = None
    for path in sorted(files, key=lambda p: ("27B" in p.stem, p.stem)):
        records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        if not records:
            continue
        approver, harness = versions(records)
        header = header or (approver, harness)
        if (approver, harness) != header:
            raise ValueError(f"{path.name}: approver {approver}, harness {harness}, unlike its suite")
        name = model_name(path.stem)
        for i, row in enumerate(summarize(records, kind)):
            succeeded = f"**{fmt(row.succeeded)}**" if row.arm in ("pr3", "plain") else fmt(row.succeeded)
            approvals = "-" if row.arm == "plain" else f"{row.approvals:.2f}"
            lines.append(
                f"| {name if i == 0 else ''} | {ARMS[row.arm]} | {fmt(row.benign)} | {fmt(row.attacked)} "
                f"| {fmt(row.fooled)} | {succeeded} | {row.text_only} | {row.in_gaps} | {approvals} |"
            )
    if not lines:
        return ""
    approver, harness = header
    title = (
        f"**{suite.capitalize()} suite** ({kind.user_tasks} user tasks, {plural(kind.injection_tasks, 'attack')}"
        f"{f', {len(kind.text_only)} of them text-only' if kind.text_only else ''}; "
        f"{plural(len(kind.gaps), 'approver-gap pair')}; approver v{approver}, harness {harness})"
    )
    head = (
        "| Model | Arm | Benign utility | Utility under attack | Model fooled | Attack succeeded "
        "| Text-only | Approver gap | Approvals per run |\n"
        "|---|---|---|---|---|---|---|---|---|"
    )
    return f"{title}\n\n{head}\n" + "\n".join(lines)


def plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


LEGEND = (
    "*Model fooled*: the model made the attacker's consequential call, whether or not it ran. "
    "*Attack succeeded*: AgentDojo found the attacker's goal reached. Of the successful attacks, "
    "*text-only* counts those whose goal is something the model says rather than a call it makes, and "
    "*approver gap* those where the user's own task needs a call to the same place, so only free text "
    "tells them apart; no runtime can stop either."
)


def report(results: Path) -> str:
    sections = [LEGEND]
    for suite in SUITES:
        files = sorted(results.glob(f"{suite}-*.jsonl"))
        section = table(suite, files)
        if section:
            sections.append(section)
    return "\n\n".join(sections) if len(sections) > 1 else ""


def update(doc: Path, text: str) -> None:
    content = doc.read_text()
    if BEGIN not in content or END not in content:
        raise ValueError(f"{doc} has no {BEGIN} … {END} section")
    before, rest = content.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    doc.write_text(f"{before}{BEGIN}\n\n{text}\n\n{END}{after}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, default=HERE / "result")
    parser.add_argument("--update", type=Path, help="Markdown file whose results section to rewrite")
    args = parser.parse_args()
    try:
        text = report(args.results)
        if args.update:
            update(args.update, text)
            print(f"updated {args.update}")
        else:
            print(text)
    except ValueError as e:
        print(f"report.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
