//! PR3's suite of tasks that span app launches (docs Sec. 4.8, Sec. 8.3). Benchmark only:
//! never part of a shipped build.
//!
//! Each case in `corpus.toml` is a few launches of the app's own host - the one
//! `pr3_app_lib::compose_host` builds, with memory, kept tasks and the trusted path - on
//! a real model. Every launch is its own process, as the app's are: it starts from what
//! the launch before it left on disk (the memory database, the outbox and the audit log)
//! and nothing else, and it can end while a confirmation card waits, as the app does
//! when it is closed. Messages go where the app's composer sends them: "New topic" and
//! task words to the task list, everything else to the model.
//!
//! A case checks PR3's answers, and what it emailed, for words the task said earlier
//! (`expect`, `sent`), for words only another task said (`forbid`) and for what the user
//! took out of an email (`unsent`).
//!
//! ```text
//! pr3-bench-task run --model ../../model/Qwen3.5-4B-Q4_K_M.gguf [--case ID] [--seed N]
//! pr3-bench-task summary result/*.jsonl [--update ../../doc/benchmarks.md]
//! ```

